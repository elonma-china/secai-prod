#!/usr/bin/env bash
# Install an hourly `systemd --user` timer that runs wt-prune.sh --yes.
#
#   scripts/install-wt-prune-timer.sh            # install + enable
#   scripts/install-wt-prune-timer.sh --remove   # disable + remove
#
# The timer runs a tiny runner (~/.local/bin/secai-wt-prune-run) that exports the scripts/ of the
# LATEST origin/main into a temp dir and runs them against the main checkout, so it neither
# depends on which commit the main checkout happens to be on nor touches its files.
# Needs `loginctl enable-linger $USER` (already on) so the user manager runs without a login.
set -euo pipefail

UNIT_DIR=$HOME/.config/systemd/user
RUNNER=$HOME/.local/bin/secai-wt-prune-run

if [ "${1:-}" = "--remove" ]; then
    systemctl --user disable --now secai-wt-prune.timer 2>/dev/null || true
    rm -f "$UNIT_DIR/secai-wt-prune.service" "$UNIT_DIR/secai-wt-prune.timer" "$RUNNER"
    systemctl --user daemon-reload
    echo "removed secai-wt-prune timer"
    exit 0
fi

MAIN=$(git worktree list --porcelain | sed -n '1s/^worktree //p')
[ -n "$MAIN" ] || { echo "install-wt-prune-timer: run inside the repo" >&2; exit 2; }

mkdir -p "$UNIT_DIR" "$(dirname "$RUNNER")"

cat > "$RUNNER" <<EOF
#!/usr/bin/env bash
# Generated by scripts/install-wt-prune-timer.sh — runs origin/main's wt-prune.sh on $MAIN.
set -euo pipefail
cd "$MAIN"
git fetch -q origin
tmp=\$(mktemp -d); trap 'rm -rf "\$tmp"' EXIT
git archive origin/main scripts | tar -x -C "\$tmp"
"\$tmp/scripts/wt-prune.sh" --yes
# image/container rollback+smoke prod quá 3 ngày
"\$tmp/scripts/release-prod.sh" gc --yes || true
EOF
chmod 755 "$RUNNER"

cat > "$UNIT_DIR/secai-wt-prune.service" <<EOF
[Unit]
Description=Prune merged git worktrees/branches and orphan dev stacks (secai-agent-gateway)

[Service]
Type=oneshot
ExecStart=$RUNNER
Nice=10
EOF

cat > "$UNIT_DIR/secai-wt-prune.timer" <<'EOF'
[Unit]
Description=Hourly prune of merged git worktrees/branches (secai-agent-gateway)

[Timer]
OnBootSec=10min
OnUnitActiveSec=1h
RandomizedDelaySec=2min

[Install]
WantedBy=timers.target
EOF

systemctl --user daemon-reload
systemctl --user enable --now secai-wt-prune.timer
systemctl --user list-timers secai-wt-prune.timer --no-pager | head -3
echo "log: \${WT_PRUNE_LOG:-~/.local/state/secai/wt-prune.log}   manual run: systemctl --user start secai-wt-prune.service"
