#!/usr/bin/env bash
# Per-worktree dev stack for the gateway (see compose.dev.yml). Production is untouched:
# it stays the `secai-docker` compose project on public :8131.
#
#   scripts/dev.sh init      # once per worktree: write .env.worktree (name/port/bind IP)
#   scripts/dev.sh up        # start (builds the image on first run); code is live-mounted
#   scripts/dev.sh rebuild   # only after changing Dockerfile / pyproject.toml / bin/
#   scripts/dev.sh health    # GET /health and check git_branch matches this worktree
#   scripts/dev.sh test [..] # pytest on THIS worktree's src (not the main checkout's)
#   scripts/dev.sh down | clean | logs | ps | info
#
# Every command prints dir/branch/project/url first, so you always know which stack you hit.
set -euo pipefail
cd "$(dirname "$0")/.."
ROOT=$PWD
WT_ENV=.env.worktree
MAIN_CHECKOUT=$(git worktree list --porcelain | sed -n '1s/^worktree //p')

die() { echo "dev.sh: $*" >&2; exit 1; }

lan_ip() {
    ip -4 route get 1.1.1.1 2>/dev/null | awk '{for (i=1;i<NF;i++) if ($i=="src") {print $(i+1); exit}}'
}

port_busy() { ss -Hltn "sport = :$1" 2>/dev/null | grep -q .; }

# Host-side .env (gitignored) is needed by pytest/settings; worktrees (incl. ones T3 Code
# creates) start without it, so copy the main checkout's, owner-only.
ensure_dotenv() {
    if [ ! -f .env ] && [ "$ROOT" != "$MAIN_CHECKOUT" ] && [ -f "$MAIN_CHECKOUT/.env" ]; then
        install -m 600 "$MAIN_CHECKOUT/.env" .env && echo "dev.sh: copied .env from $MAIN_CHECKOUT" >&2
    fi
}

cmd_init() {
    ensure_dotenv
    [ -f "$WT_ENV" ] && { echo "dev.sh: $WT_ENV already exists:"; cat "$WT_ENV"; return 0; }
    local name slug port ip
    name=$(basename "$ROOT"); name=${name#wt-}
    slug=$(printf '%s' "$name" | tr 'A-Z' 'a-z' | tr -c 'a-z0-9' '-' | sed 's/-\{2,\}/-/g; s/^-//; s/-$//' | cut -c1-30)
    # The slug is lossy (case, punctuation, 30-char cut): never reuse another worktree's
    # project, or `clean`/wt-rm there would `compose down -v` this stack (and vice versa).
    local taken n=0 base=$slug
    taken=$(git worktree list --porcelain | sed -n 's/^worktree //p' | while IFS= read -r w; do
        [ "$w" = "$ROOT" ] || sed -n 's/^COMPOSE_PROJECT_NAME=//p' "$w/$WT_ENV" 2>/dev/null || true
    done)
    while printf '%s\n' "$taken" | grep -qxF "secai-gw-dev-$slug"; do
        n=$((n + 1)); slug=$(printf '%s' "$base" | cut -c1-27)-$n
    done
    port=$((20000 + $(printf '%s' "$name" | cksum | cut -d' ' -f1) % 1000))
    while port_busy "$port"; do port=$((port + 1)); done
    ip=$(lan_ip); [ -n "$ip" ] || die "cannot detect the LAN IP; set BIND_IP in $WT_ENV by hand"
    cat > "$WT_ENV" <<EOF
# Generated by scripts/dev.sh init — per-worktree, not committed (.env.* is gitignored).
COMPOSE_PROJECT_NAME=secai-gw-dev-$slug
DEV_IMAGE=secai-agent-gateway:dev-$slug
# LAN-only on purpose: the public IP serves production :8131 only.
BIND_IP=$ip
APP_PORT=$port
# Runtime config (endpoints/keys) is read from production's env file, never copied here.
DEV_ENV_FILE=/home/ict/AIEngines/secai/secai-docker/.env
SECAI_DATA_ROOT=/home/ict/AIEngines/secai/secai-data
EOF
    chmod 600 "$WT_ENV"
    echo "dev.sh: wrote $WT_ENV -> http://$ip:$port (project secai-gw-dev-$slug)"
}

load_env() {
    [ -f "$WT_ENV" ] || cmd_init >&2
    set -a; . "./$WT_ENV"; set +a
    GIT_BRANCH=$(git branch --show-current); GIT_SHA=$(git rev-parse --short HEAD)
    export GIT_BRANCH GIT_SHA
    # Guards: a dev stack must never look like / collide with production.
    case "$COMPOSE_PROJECT_NAME" in secai-gw-dev-*) ;; *) die "COMPOSE_PROJECT_NAME must start with secai-gw-dev-";; esac
    case "$APP_PORT" in 8131|8140) die "APP_PORT $APP_PORT is reserved for production";; esac
    case "$BIND_IP" in 0.0.0.0|""|::|"[::]") die "BIND_IP must be a LAN/loopback IP, not '$BIND_IP' (public = production only)";; esac
    case "$DEV_IMAGE" in secai-agent-gateway:dev-*) ;; *) die "DEV_IMAGE must be secai-agent-gateway:dev-*";; esac
    [ -r "$DEV_ENV_FILE" ] || die "DEV_ENV_FILE not readable: $DEV_ENV_FILE"
    echo ">> dir=$ROOT branch=$GIT_BRANCH sha=$GIT_SHA project=$COMPOSE_PROJECT_NAME url=http://$BIND_IP:$APP_PORT" >&2
}

compose() { docker compose --env-file "$WT_ENV" -p "$COMPOSE_PROJECT_NAME" -f compose.dev.yml "$@"; }

build() {
    docker build -t "$DEV_IMAGE" --build-arg GIT_SHA="$GIT_SHA" --build-arg GIT_BRANCH="$GIT_BRANCH" .
}

# src/ is bind-mounted (PYTHONPATH=/app/src wins over site-packages), so the image only has to
# carry dependencies. If this branch did not touch them, reuse production's current image
# under the dev tag (seconds, no extra disk) instead of a ~9 min build.
ensure_image() {
    docker image inspect "$DEV_IMAGE" >/dev/null 2>&1 && return 0
    local base fork
    base=$(docker inspect secai-docker-gateway --format '{{.Config.Image}}' 2>/dev/null || true)
    fork=$(git merge-base HEAD origin/main 2>/dev/null || true)
    if [ -n "$base" ] && [ -n "$fork" ] && git diff --quiet "$fork" -- pyproject.toml uv.lock Dockerfile bin; then
        echo "dev.sh: deps unchanged vs main -> reusing $base as $DEV_IMAGE (run 'rebuild' to build)" >&2
        docker tag "$base" "$DEV_IMAGE"
    else
        echo "dev.sh: deps changed on this branch (or no base image) -> building $DEV_IMAGE" >&2
        build
    fi
}

cmd_health() {
    local body
    local i
    for i in $(seq 1 30); do   # uvicorn needs a few seconds after `up` / a reload
        body=$(curl -fsS --max-time 15 "http://$BIND_IP:$APP_PORT/health" 2>/dev/null) && break
        sleep 2
    done
    [ -n "${body:-}" ] || die "no answer on http://$BIND_IP:$APP_PORT/health (see: scripts/dev.sh logs)"
    printf '%s\n' "$body" | python3 -c '
import json, sys
b = json.load(sys.stdin); want = sys.argv[1] or None  # detached HEAD: /health reports null
print(json.dumps({k: b.get(k) for k in ("status", "git_branch", "git_sha", "llm", "redis")}, ensure_ascii=False))
got = b.get("git_branch")
if got != want:
    sys.exit(f"dev.sh: stack serves branch {got!r}, this worktree is {want!r} — wrong stack or stale container (run: scripts/dev.sh up)")
' "$GIT_BRANCH"
}

cmd_test() {
    local py=$ROOT/.venv/bin/python
    [ -x "$py" ] || py=$MAIN_CHECKOUT/.venv/bin/python
    [ -x "$py" ] || die "no .venv found (here or in $MAIN_CHECKOUT)"
    # The shared venv has the MAIN checkout installed in editable mode; without this, pytest
    # would silently import main's src/ instead of this worktree's.
    PYTHONPATH="$ROOT/src${PYTHONPATH:+:$PYTHONPATH}" "$py" -m pytest -q "$@"
}

case "${1:-}" in
    init) cmd_init ;;
    test) shift; ensure_dotenv; echo ">> dir=$ROOT branch=$(git branch --show-current) (pytest on this worktree's src)" >&2; cmd_test "$@" ;;
    up)      load_env; ensure_image; compose up -d ;;
    rebuild) load_env; build; compose up -d ;;
    down)    load_env; compose down ;;
    clean)   load_env; compose down -v --remove-orphans; docker image rm "$DEV_IMAGE" 2>/dev/null || true ;;
    logs)    load_env; compose logs -f --tail=100 ;;
    ps)      load_env; compose ps ;;
    health)  load_env; cmd_health ;;
    info)    load_env ;;
    *) echo "usage: $0 init|up|rebuild|down|clean|logs|ps|health|test|info" >&2; exit 2 ;;
esac
